function generateExport(steps: FormStep[], formName: string): string {
  const lines: string[] = [
    `import { useState } from 'react'`,
    '',
    `// Generated by chronoform — ${formName}`,
    '',
    'type FormData = Record<string, string | boolean>',
    '',
    `export default function ${formName.replace(/\s+/g, '')}Form() {`,
    '  const [stepId, setStepId] = useState(' + JSON.stringify(steps[0]?.id ?? 's1') + ')',
    '  const [data, setData] = useState<FormData>({})',
    '  const [submitted, setSubmitted] = useState(false)',
    '',
    '  const steps = ' + JSON.stringify(steps, null, 4).split('\n').map((l, i) => i === 0 ? l : '  ' + l).join('\n'),
    '',
    '  const step = steps.find(s => s.id === stepId)',
    '  if (!step) return null',
    '',
    '  function next() {',
    '    const branch = step.branches.find(b => {',
    '      const val = String(data[b.condition.fieldId] ?? "")',
    '      if (b.condition.operator === "equals") return val === b.condition.value',
    '      if (b.condition.operator === "not_equals") return val !== b.condition.value',
    '      if (b.condition.operator === "contains") return val.includes(b.condition.value)',
    '      if (b.condition.operator === "not_empty") return val.length > 0',
    '      return false',
    '    })',
    '    const nextId = branch?.targetStepId ?? step.defaultNextStepId',
    '    if (!nextId) { setSubmitted(true); return }',
    '    setStepId(nextId)',
    '  }',
    '',
    '  if (submitted) return <div>Submitted! Data: {JSON.stringify(data)}</div>',
    '',
    '  return (',
    '    <form onSubmit={e => { e.preventDefault(); next() }}>',
    '      <h2>{step.title}</h2>',
    '      {step.fields.map(field => (',
    '        <div key={field.id}>',
    '          <label>{field.label}</label>',
    '          <input',
    '            name={field.id}',
    '            required={field.required}',
    '            onChange={e => setData(d => ({ ...d, [field.id]: e.target.value }))}',
    '          />',
    '        </div>',
    '      ))}',
    '      <button type="submit">Next</button>',
    '    </form>',
    '  )',
    '}',
  ]
  return lines.join('\n')
}

export const useFormStore = create<FormStore>()(
  persist(
    (set, get) => ({
      steps: INITIAL_STEPS,
      selectedStepId: 's1',
      selectedFieldId: null,
      previewMode: false,
      formName: 'My Form',

      addStep: () => {
        const id = uid()
        const step: FormStep = {
          id,
          title: `Step ${get().steps.length + 1}`,
          fields: [],
          branches: [],
          defaultNextStepId: null,
        }
        set((s) => ({ steps: [...s.steps, step], selectedStepId: id }))
      },

      removeStep: (id) =>
        set((s) => ({
          steps: s.steps.filter((st) => st.id !== id),
          selectedStepId: s.selectedStepId === id ? null : s.selectedStepId,
        })),

      updateStep: (id, patch) =>
        set((s) => ({ steps: s.steps.map((st) => st.id === id ? { ...st, ...patch } : st) })),

      selectStep: (id) => set({ selectedStepId: id, selectedFieldId: null }),

      addField: (stepId, type) => {
        const id = uid()
        const field: FormField = {
          id,
          type,
          label: type.charAt(0).toUpperCase() + type.slice(1),
          placeholder: '',
          required: false,
          options: ['select', 'radio'].includes(type)
            ? [{ label: 'Option 1', value: 'opt1' }, { label: 'Option 2', value: 'opt2' }]
            : undefined,
        }
        set((s) => ({
          steps: s.steps.map((st) => st.id === stepId ? { ...st, fields: [...st.fields, field] } : st),
          selectedFieldId: id,
        }))
      },

      removeField: (stepId, fieldId) =>
        set((s) => ({
          steps: s.steps.map((st) =>
            st.id !== stepId ? st : { ...st, fields: st.fields.filter((f) => f.id !== fieldId) }
          ),
          selectedFieldId: null,
        })),

      updateField: (stepId, fieldId, patch) =>
        set((s) => ({
          steps: s.steps.map((st) =>
            st.id !== stepId ? st : {
              ...st,
              fields: st.fields.map((f) => f.id === fieldId ? { ...f, ...patch } : f),
            }
          ),
        })),

      moveField: (stepId, fieldId, direction) =>
        set((s) => ({
          steps: s.steps.map((st) => {
            if (st.id !== stepId) return st
            const idx = st.fields.findIndex((f) => f.id === fieldId)
            if (idx < 0) return st
            const newIdx = direction === 'up' ? idx - 1 : idx + 1
            if (newIdx < 0 || newIdx >= st.fields.length) return st
            const fields = [...st.fields]
            ;[fields[idx], fields[newIdx]] = [fields[newIdx], fields[idx]]
            return { ...st, fields }
          }),
        })),

      selectField: (id) => set({ selectedFieldId: id }),

      addBranch: (stepId) =>
        set((s) => ({
          steps: s.steps.map((st) =>
            st.id !== stepId ? st : {
              ...st,
              branches: [...st.branches, {
                condition: { fieldId: st.fields[0]?.id ?? '', operator: 'equals' as const, value: '' },
                targetStepId: '',
              }],
            }
          ),
        })),

      removeBranch: (stepId, index) =>
        set((s) => ({
          steps: s.steps.map((st) =>
            st.id !== stepId ? st : {
              ...st,
              branches: st.branches.filter((_, i) => i !== index),
            }
          ),
        })),

      updateBranch: (stepId, index, condition, targetStepId) =>
        set((s) => ({
          steps: s.steps.map((st) => {
            if (st.id !== stepId) return st
            return {
              ...st,
              branches: st.branches.map((b, i) => i !== index ? b : {
                condition: { ...b.condition, ...condition },
                targetStepId: targetStepId ?? b.targetStepId,
              }),
            }
          }),
        })),

      setPreviewMode: (v) => set({ previewMode: v }),
      setFormName: (n) => set({ formName: n }),

      exportCode: () => {
        const { steps, formName } = get()
        return generateExport(steps, formName)
      },
    }),
    { name: 'chronoform-store' }
  )
)
