import { create } from 'zustand'
import { persist } from 'zustand/middleware'
import type { FormStep, FormField, BranchCondition, FieldType } from '../types'

interface FormStore {
  steps: FormStep[]
  selectedStepId: string | null
  selectedFieldId: string | null
  previewMode: boolean
  formName: string

  addStep: () => void
  removeStep: (id: string) => void
  updateStep: (id: string, patch: Partial<Omit<FormStep, 'id' | 'fields' | 'branches'>>) => void
  selectStep: (id: string | null) => void

  addField: (stepId: string, type: FieldType) => void
  removeField: (stepId: string, fieldId: string) => void
  updateField: (stepId: string, fieldId: string, patch: Partial<FormField>) => void
  moveField: (stepId: string, fieldId: string, direction: 'up' | 'down') => void
  selectField: (id: string | null) => void

  addBranch: (stepId: string) => void
  removeBranch: (stepId: string, index: number) => void
  updateBranch: (stepId: string, index: number, condition: Partial<BranchCondition>, targetStepId?: string) => void

  setPreviewMode: (v: boolean) => void
  setFormName: (n: string) => void

  // Export
  exportCode: () => string
}

